"""远程访问开关：放开「只有本机能管理」的来源限制，访问口令继续生效。

服务默认只接受本机来源的管理请求：回环地址、与绑定地址相同的 IP、配置的 `.local`
名字，提交还要 Origin 与当前页面一致。局域网里通过绑定地址直接访问时，这几条判据会
把正常请求挡在 403 上。`PEACH_ALLOW_REMOTE=1` 去掉这些来源限制，管理接口与页面
只剩访问口令这一道闸门。

开关只影响来源判定。口令校验、登录尝试限速、会话 cookie 属性、非回环地址必须设置
访问口令才能启动，这些都与开关无关。环境变量会被子进程继承，所以打开开关的部署必须
同时设置访问口令；`peach serve` 在非回环地址上没有口令时拒绝启动，这条始终成立。
"""
from __future__ import annotations

import os

#: 设为 `1` 时放开本机来源限制；其他取值（包括 `0`）保持默认判定。
ENV = "PEACH_ALLOW_REMOTE"


def relaxed() -> bool:
    """是否放开来源限制。只认字面值 `1`，避免 `0`、`false` 这类写法被当成打开。"""
    return os.environ.get(ENV) == "1"


def startup_notice() -> str:
    """启动时打印的提示句；开关没打开时返回空串。"""
    if not relaxed():
        return ""
    return f"{ENV}=1：已放开本机来源限制，管理接口按访问口令鉴权。"
